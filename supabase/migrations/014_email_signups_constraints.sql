-- Run this in Supabase → SQL Editor.
--
-- email_signups was created by hand in the dashboard, so it never had a
-- migration. This one records its current shape and tightens it:
--
--   * created_at was already fine (timestamptz, not null, default now()) —
--     restated here only so the schema lives in the repo.
--   * email was nullable and not unique, and the newsletter and coming-soon
--     forms had stored the same address more than once (different case /
--     spacing). Emails are now normalized to lower(trim()) on insert,
--     existing duplicates are collapsed to the earliest signup, and email is
--     required and unique.
--
-- The forms treat a unique violation (23505) as success, so someone signing
-- up twice still sees "joined".

create table if not exists public.email_signups (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  email text
);

-- Normalize existing rows, then keep only the earliest signup per address.
update public.email_signups
  set email = lower(btrim(email))
  where email is not null and email <> lower(btrim(email));

delete from public.email_signups
  where email is null or email = '';

delete from public.email_signups a
  using public.email_signups b
  where a.email = b.email
    and (a.created_at, a.id) > (b.created_at, b.id);

alter table public.email_signups
  alter column email set not null;

alter table public.email_signups
  drop constraint if exists email_signups_email_key;
alter table public.email_signups
  add constraint email_signups_email_key unique (email);

-- Normalize on every insert so "Foo@Bar.com " and "foo@bar.com" collide.
create or replace function public.email_signups_normalize()
returns trigger
language plpgsql
as $$
begin
  new.email := lower(btrim(new.email));
  return new;
end;
$$;

drop trigger if exists email_signups_normalize on public.email_signups;
create trigger email_signups_normalize
  before insert or update of email on public.email_signups
  for each row execute function public.email_signups_normalize();
