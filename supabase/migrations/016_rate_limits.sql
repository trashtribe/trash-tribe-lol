-- Run this in Supabase → SQL Editor, AFTER the code that adds
-- /api/newsletter is deployed (otherwise the newsletter form briefly breaks).
--
-- 1. rate_limit_events: one row per contact/newsletter submission, keyed by
--    a hashed client IP. lib/rate-limit.ts counts recent rows to decide
--    whether to accept the next one. Only the service-role key touches it
--    (RLS on, no policies). Rows older than a day are deleted by the daily
--    /api/health cron.
--
-- 2. email_signups: signups now go through /api/newsletter (honeypot +
--    rate limit + service-role insert), so the anon "allow_insert" policy
--    that let anyone insert straight from the browser goes away.

create table if not exists public.rate_limit_events (
  id bigint generated by default as identity primary key,
  bucket text not null,
  key_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists rate_limit_events_lookup
  on public.rate_limit_events (bucket, key_hash, created_at desc);

alter table public.rate_limit_events enable row level security;

-- Drop every INSERT policy on email_signups, whatever it's called (live one
-- is "allow_insert", made in the dashboard).
do $$
declare
  p record;
begin
  for p in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'email_signups'
      and cmd in ('INSERT', 'ALL')
  loop
    execute format('drop policy %I on public.email_signups', p.policyname);
  end loop;
end $$;

alter table public.email_signups enable row level security;
